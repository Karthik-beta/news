// Generates the component registry from the folders in src/components/ (the folder contract in
// src/components/README.md). Runs before dev, build and test; a unit test fails if the committed output is stale.
//   src/components/registry.generated.ts   every spec.ts, for the OpenUI library and component-index.json
//   src/components/islands.generated.ts    every <Name>.client.tsx, loaded on demand by the island hydrator
//   src/styles/components.generated.css    every component's stylesheet, in one place for the shell build
// It also checks each folder against the contract and exits non-zero with the problems.
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const site = join(dirname(fileURLToPath(import.meta.url)), "..");
const componentsDir = join(site, "src/components");

const HEADER = "GENERATED by site/scripts/gen-components.ts from the folders in src/components/. Do not edit.";

export interface Generated {
  files: Record<string, string>;
  problems: string[];
}

export function componentFolders(dir = componentsDir): string[] {
  return readdirSync(dir)
    .filter((name) => /^[A-Z][A-Za-z0-9]*$/.test(name) && statSync(join(dir, name)).isDirectory())
    .sort();
}

/** Contract problems for one folder: the files every component and primitive must have. */
export function folderProblems(dir: string, name: string): string[] {
  const at = (f: string) => join(dir, name, f);
  const problems: string[] = [];
  for (const f of [`${name}.tsx`, "spec.ts", "SIGNOFF.md"]) {
    if (!existsSync(at(f))) problems.push(`${name}: missing ${f}`);
  }
  if (!existsSync(at("fixtures")) || readdirSync(at("fixtures")).length === 0) {
    problems.push(`${name}: fixtures/ is missing or empty`);
  }
  if (existsSync(at("spec.ts"))) {
    const spec = readFileSync(at("spec.ts"), "utf8");
    if (!/export default define(NewsComponent|RootComponent|Primitive)\(/.test(spec)) {
      problems.push(
        `${name}: spec.ts must \`export default\` defineNewsComponent, defineRootComponent or definePrimitive`,
      );
    }
    if (!new RegExp(`name: "${name}"`).test(spec)) problems.push(`${name}: spec.ts name must be "${name}"`);
  }
  return problems;
}

export function generate(dir = componentsDir): Generated {
  const folders = componentFolders(dir);
  const problems = folders.flatMap((name) => folderProblems(dir, name));
  const ident = (name: string) => `${name.charAt(0).toLowerCase()}${name.slice(1)}Spec`;

  const registry = [
    `// ${HEADER}`,
    'import type { AnySpec } from "./contract";',
    ...folders.map((name) => `import ${ident(name)} from "./${name}/spec";`),
    "",
    `export const specs: readonly AnySpec[] = [${folders.map(ident).join(", ")}];`,
    "",
  ].join("\n");

  const islands = folders.flatMap((name) =>
    readdirSync(join(dir, name))
      .filter((f) => f.endsWith(".client.tsx"))
      .map((f) => ({ name: f.replace(/\.client\.tsx$/, ""), path: `./${name}/${f.replace(/\.tsx$/, "")}` })),
  );
  const islandsFile = [
    `// ${HEADER}`,
    "// Island components by name, loaded only when a page has one. Server and client agree on these names.",
    'import type { IslandLoaders } from "../renderer/islands/types";',
    "",
    "export const islands: IslandLoaders = {",
    ...islands.map((i) => `  ${i.name}: () => import("${i.path}"),`),
    "};",
    "",
  ].join("\n");

  const css = [
    `/* ${HEADER} */`,
    ...folders
      .filter((name) => existsSync(join(dir, name, `${name}.css`)))
      .map((name) => `@import "../components/${name}/${name}.css";`),
    "",
  ].join("\n");

  return {
    files: {
      "src/components/registry.generated.ts": registry,
      "src/components/islands.generated.ts": islandsFile,
      "src/styles/components.generated.css": css,
    },
    problems,
  };
}

if (import.meta.main) {
  const { files, problems } = generate();
  for (const [path, text] of Object.entries(files)) writeFileSync(join(site, path), text);
  if (problems.length > 0) {
    console.error(`Component folders break the contract (src/components/README.md):\n  ${problems.join("\n  ")}`);
    process.exit(1);
  }
  console.log(`component registry generated (${componentFolders().length} folders)`);
}
