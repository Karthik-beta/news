//! Generates Board's theme from `design/tokens/tokens.json` (the source of truth, ADR 0007 decision 5):
//! the light and dark colour tables, the type sizes, spacing, radii and borders, as Rust constants.
//! Board code never writes a colour or a size by hand; a test fails on literal colours in `src/`.

use serde_json::Value;
use std::fmt::Write as _;
use std::path::PathBuf;

fn hex(v: &Value) -> [u8; 3] {
    let s = v
        .as_str()
        .unwrap_or_else(|| panic!("colour token is not a string: {v}"));
    let h = s.trim_start_matches('#');
    assert_eq!(h.len(), 6, "colour {s} is not #RRGGBB");
    let n = u32::from_str_radix(h, 16).unwrap_or_else(|_| panic!("bad colour {s}"));
    [(n >> 16) as u8, (n >> 8) as u8, n as u8]
}

fn ident(key: &str) -> String {
    key.replace('-', "_")
}

/// A dimension token's value in px (`rem` is 16 px).
fn px(v: &Value) -> f64 {
    let n = v["value"]
        .as_f64()
        .unwrap_or_else(|| panic!("no value in {v}"));
    match v["unit"].as_str() {
        Some("rem") => n * 16.0,
        Some("px") => n,
        other => panic!("unit {other:?} is not a screen size"),
    }
}

fn main() {
    let root = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap_or_default())
        .join("../../../design/tokens/tokens.json");
    println!("cargo:rerun-if-changed={}", root.display());
    let text = std::fs::read_to_string(&root)
        .unwrap_or_else(|e| panic!("cannot read {}: {e}", root.display()));
    let t: Value =
        serde_json::from_str(&text).unwrap_or_else(|e| panic!("tokens.json is not JSON: {e}"));

    let colors = t["color"]
        .as_object()
        .unwrap_or_else(|| panic!("no color group"));
    let names: Vec<&String> = colors.keys().filter(|k| !k.starts_with('$')).collect();
    let mut out =
        String::from("// GENERATED by build.rs from design/tokens/tokens.json. Do not edit.\n\n");
    out.push_str(
        "/// One mode's colours as RGB.\n#[derive(Debug, Clone, Copy)]\npub struct Palette {\n",
    );
    for n in &names {
        let _ = writeln!(out, "    pub {}: [u8; 3],", ident(n));
    }
    out.push_str("}\n\n");
    for (label, dark) in [("LIGHT", false), ("DARK", true)] {
        let _ = writeln!(out, "pub const {label}: Palette = Palette {{");
        for n in &names {
            let tok = &colors[*n];
            let v = if dark {
                tok["$extensions"]["news.dark"]
                    .as_str()
                    .map(|_| &tok["$extensions"]["news.dark"])
            } else {
                None
            }
            .unwrap_or(&tok["$value"]);
            let [r, g, b] = hex(v);
            let _ = writeln!(out, "    {}: [{r}, {g}, {b}],", ident(n));
        }
        out.push_str("};\n\n");
    }

    let groups: [(&str, &str); 5] = [
        ("size", "font"),
        ("space", "space"),
        ("radius", "radius"),
        ("border", "border"),
        ("layout", "layout"),
    ];
    for (module, group) in groups {
        let node = if group == "font" {
            &t["font"]["size"]
        } else {
            &t[group]
        };
        let _ = writeln!(out, "pub mod {module} {{");
        for (k, v) in node.as_object().unwrap_or_else(|| panic!("no token group")) {
            if k.starts_with('$') || v.get("$value").is_none() {
                continue;
            }
            let value = &v["$value"];
            // `ch` sizes (the prose measure) are not screen sizes.
            if value["unit"].as_str() == Some("ch") {
                continue;
            }
            let name = ident(k).to_uppercase();
            let name = if name.chars().next().is_some_and(|c| c.is_ascii_digit()) {
                format!("S{name}")
            } else {
                name
            };
            let _ = writeln!(out, "    pub const {name}: f32 = {:.3};", px(value));
        }
        out.push_str("}\n\n");
    }
    let dest = PathBuf::from(std::env::var("OUT_DIR").unwrap_or_default()).join("tokens.rs");
    std::fs::write(&dest, out).unwrap_or_else(|e| panic!("cannot write tokens.rs: {e}"));
}
