// Consistency checks between the files the setup scripts depend on. They fail when one is edited
// without the other (for example a new ${VAR} in the compose file with no entry in .env.example).
import { describe, expect, test } from "bun:test";
import { existsSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { getEnvValue } from "../env-file";
import { root } from "../lib";

const read = (p: string) => readFileSync(join(root, p), "utf8");
const pkg = JSON.parse(read("package.json")) as { scripts: Record<string, string>; workspaces: string[] };
const example = read(".env.example");
const exampleKeys = new Set([...example.matchAll(/^([A-Z][A-Z0-9_]*)=/gm)].map((m) => m[1] as string));

describe("root package.json scripts", () => {
  test("every `bun <file>` script points at a file that exists", () => {
    for (const [name, cmd] of Object.entries(pkg.scripts)) {
      const m = cmd.match(/^bun (?!--|run |test)(\S+\.(?:ts|mjs|js))/);
      if (m) expect(existsSync(join(root, m[1] as string)), `${name}: ${cmd}`).toBe(true);
    }
  });

  test("docker compose scripts go through the wrapper that passes .env values literally", () => {
    // --no-env-file: Bun must not load .env into the wrapper's environment, or the wrapper could not tell an
    // exported shell variable (which wins) from Bun's `$`-expanded copy of the .env value.
    for (const name of ["infra:up", "infra:down", "infra:logs", "setup"]) {
      expect(pkg.scripts[name] ?? "", name).toMatch(/^bun --no-env-file scripts\/(compose|setup)\.ts/);
    }
    expect(read("scripts/setup.ts")).toMatch(/"--no-env-file",\s*"scripts\/compose\.ts"/);
    const wrapper = readFileSync(join(root, "scripts/compose.ts"), "utf8");
    expect(wrapper).toContain('"-f", "infra/docker-compose.yml"');
    expect(wrapper).not.toContain("--env-file");
    expect(existsSync(join(root, "infra/docker-compose.yml"))).toBe(true);
  });

  test("infra:up waits for health checks and runs detached", () => {
    expect(pkg.scripts["infra:up"]).toMatch(/up -d --wait$/);
  });

  test("test:integration also runs the CLI's Postgres tests, which no Bun workspace reaches", () => {
    // postgres.rs, ci.yml and CLAUDE.md all point at `bun run test:integration` for these tests.
    expect(pkg.scripts["test:integration"]).toContain("bun scripts/test-cli.ts integration");
    expect(read("cli/crates/news/tests/postgres.rs")).toContain("bun run test:integration");
  });

  test("every workspace directory exists and has a package.json", () => {
    for (const w of pkg.workspaces.filter((p) => !p.includes("*")))
      expect(existsSync(join(root, w, "package.json")), w).toBe(true);
  });
});

describe(".env.example", () => {
  test("the keys setup generates exist, and start empty so setup fills them", () => {
    for (const key of ["NEWS_PG_PASSWORD", "NEWS_CH_PASSWORD", "DATABASE_URL"]) {
      expect(exampleKeys.has(key), key).toBe(true);
      expect(getEnvValue(example, key), `${key} must be empty in the template`).toBe("");
    }
  });

  test("holds no secret values: tokens, passwords and keys are blank", () => {
    for (const key of ["CLOUDFLARE_API_TOKEN", "NEWS_WRITE_API_KEY", "NEWS_PG_PASSWORD", "NEWS_CH_PASSWORD"])
      expect(getEnvValue(example, key), key).toBe("");
  });

  test("every variable the compose file reads is in .env.example or has a default", () => {
    const compose = read("infra/docker-compose.yml");
    const refs = [...compose.matchAll(/\$\{([A-Z][A-Z0-9_]*)(:?[-?][^}]*)?\}/g)];
    expect(refs.length).toBeGreaterThan(0);
    for (const [, name, modifier] of refs) {
      const hasDefault = modifier?.startsWith(":-") || modifier?.startsWith("-");
      expect(hasDefault || exampleKeys.has(name as string), `${name} is used in docker-compose.yml`).toBe(true);
    }
  });

  test("variables compose requires (:?) are generated by setup", () => {
    const compose = read("infra/docker-compose.yml");
    const required = [...compose.matchAll(/\$\{([A-Z][A-Z0-9_]*):\?/g)].map((m) => m[1] as string);
    const generatedBySetup = ["NEWS_PG_PASSWORD", "NEWS_CH_PASSWORD"];
    for (const name of required) expect(generatedBySetup, `${name} is required by compose`).toContain(name);
  });

  test("the default Postgres port matches the compose default and the CLI test layer", () => {
    expect(getEnvValue(example, "NEWS_PG_PORT")).toBe("5433");
    expect(read("infra/docker-compose.yml")).toMatch(/\$\{NEWS_PG_PORT:-5433\}:5432/);
  });
});

describe(".gitignore", () => {
  const ignore = read(".gitignore").split(/\r?\n/);

  test("keeps .env out of git but .env.example in", () => {
    expect(ignore).toContain(".env");
    expect(ignore).toContain("!.env.example");
  });
});

describe("infra/postgres/init", () => {
  test("creates the three extensions the CLI's Postgres tests expect, idempotently", () => {
    const sql = read("infra/postgres/init/001_extensions.sql");
    for (const ext of ["vector", "pg_trgm", "unaccent"])
      expect(sql, ext).toMatch(new RegExp(`CREATE EXTENSION IF NOT EXISTS ${ext};`));
  });
});
